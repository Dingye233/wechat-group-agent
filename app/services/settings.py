async def get_settings(db: AsyncSession) -> dict[str, Any]:
    merged = dict(DEFAULT_SETTINGS)
    rows = (await db.execute(select(Setting))).scalars().all()
    for row in rows:
        if row.key in PUBLIC_KEYS:
            merged[row.key] = row.value
    return merged


async def get_setting(db: AsyncSession, key: str, default: Any = None) -> Any:
    data = await get_settings(db)
    return data.get(key, default)


def public_settings(data: dict[str, Any]) -> dict[str, Any]:
    result = {key: data.get(key) for key in PUBLIC_KEYS if key != "llm_api_key"}
    key = str(data.get("llm_api_key") or "")
    result["llm_configured"] = bool(key)
    result["llm_api_key_set"] = bool(key)
    result["llm_api_key_hint"] = f"••••{key[-4:]}" if len(key) >= 4 else ""
    result["demo_mode"] = not bool(key)
    result["timezone_options"] = [
        {"value": value, "label": label} for value, label in _TIMEZONES.items()
    ]
    return result


def _clean_str(value: Any, key: str) -> str:
    if not isinstance(value, str):
        raise ValueError(f"{key} 必须是字符串")
    value = value.strip()
    if len(value) > MAX_STRING:
        raise ValueError(f"{key} 内容过长")
    return value


def _clean_prompt(value: Any, key: str) -> str:
    if not isinstance(value, str):
        raise ValueError(f"{key} 必须是字符串")
    value = value.strip()
    if len(value) > MAX_PROMPT:
        raise ValueError(f"{key} 不能超过 {MAX_PROMPT} 字")
    return value


async def update_settings(
    db: AsyncSession, payload: dict[str, Any]
) -> dict[str, Any]:
    current = await get_settings(db)
    updates: dict[str, Any] = {}

    for key in (
        "llm_base_url",
        "llm_model",
        "timezone",
        "bot_aliases",
        "wcf_wechat_exe",
        "replica_wechat_exe",
        "replica_db_dir",
        "assistant_workspace",
        "auto_login",
        "default_trigger_mode",
        "memory_engine",
        "mem0_collection",
        "tray_close_action",
        "takeover_hotkey",
        "operator_engine",
        "dsh_channel",
        "group_chat_engine",
        "group_channel_mode",
    ):
        if key in payload and payload[key] is not None:
            updates[key] = _clean_str(payload[key], key)

    for key in (
        "default_persona",
        "operator_persona",
        "operator_prompt_extra",
        "operator_system_prompt",
        "group_prompt_extra",
        "group_system_prompt",
        "memory_prompt_template",
    ):
        if key in payload and payload[key] is not None:
            updates[key] = _clean_prompt(payload[key], key)

    if "llm_base_url" in updates:
        url = updates["llm_base_url"]
        if not (url.startswith("http://") or url.startswith("https://")):
            raise ValueError("API Base URL 必须以 http:// 或 https:// 开头")
    if "llm_model" in updates and not updates["llm_model"]:
        raise ValueError("模型名称不能为空")
    if "timezone" in updates:
        try:
            ZoneInfo(updates["timezone"])
        except Exception as exc:
            raise ValueError(f"无效时区：{updates['timezone']}") from exc
    if "auto_login" in updates and updates["auto_login"] not in VALID_ADAPTERS:
        raise ValueError("auto_login 只能是 mock、replica、wcf 或留空")
    if "default_trigger_mode" in updates:
        if updates["default_trigger_mode"] not in VALID_TRIGGER_MODES:
            raise ValueError("默认触发方式无效")
    if "memory_engine" in updates:
        if updates["memory_engine"] not in {"auto", "mem0", "sqlite"}:
            raise ValueError("memory_engine 只能是 auto、mem0 或 sqlite")
    if "operator_engine" in updates:
        if updates["operator_engine"] not in {"opencode", "dsh"}:
            raise ValueError("operator_engine 只能是 opencode 或 dsh")
    if "dsh_channel" in updates:
        if updates["dsh_channel"] not in {"stable", "alpha"}:
            raise ValueError("dsh_channel 只能是 stable 或 alpha")
    if "group_chat_engine" in updates:
        if updates["group_chat_engine"] not in {"dsh", "legacy"}:
            raise ValueError("group_chat_engine 只能是 dsh 或 legacy")
    if "group_channel_mode" in updates:
        if updates["group_channel_mode"] not in {"dsh_primary", "legacy"}:
            raise ValueError("group_channel_mode 只能是 dsh_primary 或 legacy")
    if "tray_close_action" in updates:
        if updates["tray_close_action"] not in {"tray", "exit"}:
            raise ValueError("tray_close_action 只能是 tray 或 exit")
    if "takeover_hotkey" in updates:
        hotkey = str(updates["takeover_hotkey"] or "").strip()
        if hotkey:
            try:
                from app.services.hotkey import parse_hotkey

                parse_hotkey(hotkey)
                updates["takeover_hotkey"] = parse_hotkey(hotkey)[2]
            except ValueError as exc:
                raise ValueError(f"暂停快捷键无效：{exc}") from exc

    if "llm_api_key" in payload and payload["llm_api_key"] is not None:
        key = _clean_str(payload["llm_api_key"], "llm_api_key")
        if key:
            updates["llm_api_key"] = key
    if payload.get("clear_api_key"):
        updates["llm_api_key"] = ""

    number_rules = {
        "llm_temperature": (0.0, 2.0, float),
        "llm_max_tokens": (64, 2000, int),
        "context_messages": (4, 50, int),
        "reply_delay_seconds": (0.0, 10.0, float),
        "reply_delay_random_seconds": (0.0, 30.0, float),
        "reply_cooldown_jitter_seconds": (0.0, 300.0, float),
        "reply_global_interval_seconds": (0.0, 300.0, float),
        "read_poll_interval_seconds": (0.5, 300.0, float),
        "memory_search_timeout_seconds": (0.3, 8.0, float),
        "memory_summary_max_input_chars": (1000, 30000, int),
        "memory_summary_max_tokens": (100, 2000, int),
        "memory_summary_max_items": (1, 12, int),
        "memory_context_items": (1, 30, int),
        "memory_context_max_chars": (200, 8000, int),
        "memory_forgetting_days": (7, 3650, int),
        "assistant_max_steps": (0, 500, int),
        "assistant_max_tokens": (128, 3000, int),
        "assistant_shell_timeout": (5, 600, int),
    }
    for key, (low, high, caster) in number_rules.items():
        if key in payload and payload[key] is not None:
            try:
                value = caster(payload[key])
            except (TypeError, ValueError) as exc:
                raise ValueError(f"{key} 必须是数字") from exc
            if not low <= value <= high:
                raise ValueError(f"{key} 需在 {low} 到 {high} 之间")
            updates[key] = value

    if "llm_json_mode" in payload and payload["llm_json_mode"] is not None:
        updates["llm_json_mode"] = bool(payload["llm_json_mode"])
    if (
        "memory_always_include" in payload
        and payload["memory_always_include"] is not None
    ):
        updates["memory_always_include"] = bool(payload["memory_always_include"])
    if (
        "memory_forgetting_enabled" in payload
        and payload["memory_forgetting_enabled"] is not None
    ):
        updates["memory_forgetting_enabled"] = bool(
            payload["memory_forgetting_enabled"]
        )
    if "seed_sample_stickers" in payload and payload["seed_sample_stickers"] is not None:
        updates["seed_sample_stickers"] = bool(payload["seed_sample_stickers"])
    if "opencode_enabled" in payload and payload["opencode_enabled"] is not None:
        updates["opencode_enabled"] = bool(payload["opencode_enabled"])
    if "dsh_enabled" in payload and payload["dsh_enabled"] is not None:
        updates["dsh_enabled"] = bool(payload["dsh_enabled"])
    if (
        "auto_retry_failed_sends" in payload
        and payload["auto_retry_failed_sends"] is not None
    ):
        updates["auto_retry_failed_sends"] = bool(
            payload["auto_retry_failed_sends"]
        )
    if (
        "read_media_download_enabled" in payload
        and payload["read_media_download_enabled"] is not None
    ):
        updates["read_media_download_enabled"] = bool(
            payload["read_media_download_enabled"]
        )
    if (
        "fast_chat_planner" in payload
        and payload["fast_chat_planner"] is not None
    ):
        updates["fast_chat_planner"] = bool(payload["fast_chat_planner"])
    if "default_keywords" in payload and payload["default_keywords"] is not None:
        value = payload["default_keywords"]
        if not isinstance(value, list):
            raise ValueError("default_keywords 必须是数组")
        keywords = [str(item).strip() for item in value if str(item).strip()]
        updates["default_keywords"] = keywords[:30]

    for key, value in updates.items():
        row = await db.get(Setting, key)
        if row is None:
            db.add(Setting(key=key, value=value))
        else:
            row.value = value
    await db.commit()

    merged = dict(current)
    merged.update(updates)
    return merged


def now_in_timezone(timezone: str) -> datetime:
    try:
        return datetime.now(ZoneInfo(timezone))
    except Exception:
        return datetime.now(ZoneInfo("Asia/Shanghai"))
